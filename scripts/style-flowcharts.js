#!/usr/bin/env node
/**
 * Apply the house flowchart style to diagrams-src/<page>/architecture.mmd.
 *
 * Black-on-white nodes, blue solid edges for the request path, purple dashed
 * for async/return. Link indices are computed from the file rather than
 * hand-counted, so edges can be reordered without silently mis-colouring.
 *
 * Idempotent: an existing generated block is replaced, not stacked.
 */
const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const SRC = path.join(ROOT, 'diagrams-src');
const MARK = '%% --- style (generated by scripts/style-flowcharts.js) ---';

const NODE = /^\s*([A-Za-z][\w]*)\s*[\("\[]/;
const EDGE = /-{1,2}\.?-{0,2}>|--[-]?\|/;

let touched = 0;
for (const page of fs.readdirSync(SRC)) {
  const file = path.join(SRC, page, 'architecture.mmd');
  if (!fs.existsSync(file)) continue;
  let text = fs.readFileSync(file, 'utf8');
  if (!/^\s*flowchart/m.test(text)) continue;

  // drop any previously generated block so re-running is safe
  const cut = text.indexOf(MARK);
  if (cut !== -1) text = text.slice(0, cut).replace(/\s+$/, '') + '\n';

  const lines = text.split('\n');
  const nodes = new Set();
  const solid = [];
  const dashed = [];
  let edgeIdx = 0;

  for (const line of lines) {
    if (/^\s*(flowchart|%%|classDef|class |linkStyle|subgraph|end)/.test(line)) continue;
    const isEdge = EDGE.test(line);
    if (isEdge) {
      // node ids referenced on an edge line still count as declared elsewhere
      (line.match(/\b[A-Za-z][\w]*\b(?=\s*(?:\(|\[|-|=|$))/g) || []).forEach((n) => {});
      (line.includes('-.') ? dashed : solid).push(edgeIdx);
      edgeIdx++;
    } else {
      const m = line.match(NODE);
      if (m) nodes.add(m[1]);
    }
  }
  // node ids that only appear on edge lines (e.g. A --> B where B declared inline)
  for (const line of lines) {
    if (!EDGE.test(line)) continue;
    const bare = line.split(/-{1,2}\.?-{0,2}>|\|/);
    bare.forEach((seg) => {
      const m = seg.trim().match(/^([A-Za-z][\w]*)\s*(?:\(|\[|$)/);
      if (m) nodes.add(m[1]);
    });
  }

  if (!nodes.size) continue;
  const out = [
    text.replace(/\s+$/, ''),
    '',
    MARK,
    '    classDef n fill:#ffffff,stroke:#111111,stroke-width:1.6px;',
    `    class ${[...nodes].join(',')} n;`,
    solid.length ? `    linkStyle ${solid.join(',')} stroke:#2f4fd0,stroke-width:1.6px;` : '',
    dashed.length ? `    linkStyle ${dashed.join(',')} stroke:#7a2f6d,stroke-width:1.6px;` : '',
    '',
  ].filter((l) => l !== '').join('\n');

  fs.writeFileSync(file, out + '\n');
  touched++;
}
console.log(`styled ${touched} flowchart(s)`);
